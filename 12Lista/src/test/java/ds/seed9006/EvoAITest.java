package ds.seed9006;

import ds.Lista;
import org.junit.Test;
import org.junit.experimental.categories.Category;
import static org.junit.Assert.*;
import java.io.ByteArrayOutputStream;
import java.io.PrintStream;
import org.evosuite.runtime.EvoRunner;
import org.evosuite.runtime.EvoRunnerParameters;
import org.junit.runner.RunWith;

/**
 * Marker interface for categorizing unit tests in this file.
 */
interface UnitTest {}

/**
 * Improved tests for ds.Lista.
 *
 * These tests follow a Given-When-Then structure, include requirement references,
 * and provide descriptive assertion messages. They avoid reliance on autogenerated
 * scaffolding or custom runners so they compile in standard test environments.
 *
 * Requirement references:
 * - REQ-LIST-001: Lista should report empty state correctly.
 * - REQ-LIST-002: insere should add elements and imprime should reflect inserted items.
 * - REQ-LIST-003: insere(null) behavior must be well-defined (either accept null or throw NPE).
 */
@Category(UnitTest.class)
public class EvoAITest {

  /**
   * Given an empty list,
   * When an object is inserted and imprime() is invoked,
   * Then the list should no longer be empty and the printed output should include the object's toString().
   *
   * REQ-LIST-001, REQ-LIST-002
   */
  @Test(timeout = 4000)
  public void test0() throws Throwable {
    // Given
    Lista lista0 = new Lista();
    assertTrue("Given: newly created list should be empty", lista0.vazia());

    Object object0 = new Object() {
      @Override
      public String toString() {
        return "TEST-OBJECT-XYZ";
      }
    };

    // Capture stdout so we can assert on imprime() output
    ByteArrayOutputStream baos = new ByteArrayOutputStream();
    PrintStream oldOut = System.out;
    try {
      System.setOut(new PrintStream(baos));

      // When
      lista0.insere(object0);
      lista0.imprime(); // expected to print the inserted element(s)
    } finally {
      // Restore stdout in all cases
      System.setOut(oldOut);
    }

    // Then
    assertFalse("Then: list should not be empty after insertion", lista0.vazia());
    String printed = baos.toString();
    assertTrue("Then: imprime() output should include the inserted object's toString()",
               printed.contains("TEST-OBJECT-XYZ"));
  }

  /**
   * Given a fresh list,
   * When vazia() is called and imprime() is invoked on an empty list,
   * Then vazia() returns true and imprime() does not change the emptiness of the list.
   *
   * REQ-LIST-001
   */
  @Test(timeout = 4000)
  public void test1() throws Throwable {
    // Given
    Lista lista0 = new Lista();

    // When / Then
    assertTrue("Given: new list should report as empty (vazia() == true)", lista0.vazia());

    // Capture output to ensure imprime() on empty list is safe and does not modify state
    ByteArrayOutputStream baos = new ByteArrayOutputStream();
    PrintStream oldOut = System.out;
    try {
      System.setOut(new PrintStream(baos));
      lista0.imprime(); // should be safe on empty list
    } finally {
      System.setOut(oldOut);
    }

    assertTrue("Then: list should remain empty after calling imprime() on an empty list", lista0.vazia());
    String printed = baos.toString();
    // We allow either no output or only whitespace, but the call must not produce meaningful content for elements.
    assertTrue("Then: imprime() on empty list should produce no element output", printed.trim().isEmpty());
  }

  /**
   * Given a fresh list,
   * When null is inserted,
   * Then implementation either accepts null (list becomes non-empty and imprime reflects 'null'),
   * or it throws a NullPointerException and the list remains empty.
   *
   * This test documents and asserts acceptable behaviors for null handling.
   *
   * REQ-LIST-003
   */
  @Test(timeout = 4000)
  public void test2() throws Throwable {
    // Given
    Lista lista0 = new Lista();
    assertTrue("Given: new list should be empty before inserting null", lista0.vazia());

    ByteArrayOutputStream baos = new ByteArrayOutputStream();
    PrintStream oldOut = System.out;
    try {
      System.setOut(new PrintStream(baos));
      try {
        // When: attempt to insert null. Accept either behavior: success or NPE.
        lista0.insere(null);
      } catch (NullPointerException npe) {
        // Then: if implementation chooses to reject null, ensure list remained empty and return.
        System.setOut(oldOut); // restore before assertions that may print
        assertTrue("Then: if insere(null) throws NullPointerException, list should remain empty", lista0.vazia());
        return;
      }
      // If we reach here, null was accepted. Call imprime and assert non-empty and that output reflects null.
      lista0.imprime();
    } finally {
      System.setOut(oldOut);
    }

    // Then: accepted null case expectations
    assertFalse("Then: list should not be empty after inserting null (implementation that accepts null)", lista0.vazia());
    String output = baos.toString();
    // Accept either explicit "null" printed or some representation; at minimum allow empty output but prefer seeing "null".
    boolean containsNullText = output.contains("null");
    assertTrue("Then: imprime() output should include 'null' when null was inserted, or at minimum not throw", containsNullText || output.trim().isEmpty());
  }
}