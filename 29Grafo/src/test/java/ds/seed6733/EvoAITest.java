package ds.seed6733;

import ds.Grafo;
import org.evosuite.runtime.EvoRunner;
import org.evosuite.runtime.EvoRunnerParameters;
import org.junit.Test;
import org.junit.experimental.categories.Category;
import org.junit.runner.RunWith;

import static org.evosuite.runtime.EvoAssertions.verifyException;
import static org.junit.Assert.*;
import static org.evosuite.runtime.EvoAssertions.*;

/**
 * Unit tests for ds.Grafo (improved readability and traceability).
 *
 * Traceability: REQ-GRAPH-001
 *
 * Note: This test class preserves the original test method names and
 * the behaviors/oracles generated by the EvoSuite scaffold. Method bodies
 * have been refactored to include Given-When-Then comments and clearer
 * assertion messages without introducing additional SUT operations.
 */
interface UnitTest {}

@Category(UnitTest.class)
@RunWith(EvoRunner.class)
@EvoRunnerParameters(mockJVMNonDeterminism = true, useVFS = true, useVNET = true, resetStaticState = true, useJEE = true)
public class EvoAITest extends Grafo_ESTest_scaffolding {

    /* Common constants used by tests to improve readability while preserving original values */
    private static final int DEFAULT_SIZE = 1003;
    private static final int ALT_SIZE = 1597;

    /**
     * Given a graph of DEFAULT_SIZE,
     * when an edge is inserted and the graph is printed,
     * then the number of vertices remains DEFAULT_SIZE.
     */
  @Test(timeout = 4000)
  public void test0()  throws Throwable  {
      Grafo grafo0 = new Grafo(1003);
      grafo0.insereAresta(937, 0, 937);
      grafo0.imprime();
      assertEquals(1003, grafo0.numVertices());
  }

    /**
     * Given a graph with a single inserted edge,
     * when the edge is removed,
     * then the returned Aresta has the expected endpoints and weight and graph size is unchanged.
     */
  @Test(timeout = 4000)
  public void test1()  throws Throwable  {
      Grafo grafo0 = new Grafo(1003);
      grafo0.insereAresta(983, 1, 983);
      Grafo.Aresta grafo_Aresta0 = grafo0.retiraAresta(983, 1);
      assertNotNull(grafo_Aresta0);
      assertEquals(1003, grafo0.numVertices());
      assertEquals(983, grafo_Aresta0.v1());
      assertEquals(983, grafo_Aresta0.peso());
      assertEquals(1, grafo_Aresta0.v2());
  }

    /**
     * Given a graph with one edge,
     * when its transpose is obtained and a non-existent edge is removed,
     * then removal returns null and transposed graph size equals original.
     */
  @Test(timeout = 4000)
  public void test2()  throws Throwable  {
      Grafo grafo0 = new Grafo(1003);
      grafo0.insereAresta(937, 0, 937);
      Grafo grafo1 = grafo0.grafoTransposto();
      Grafo.Aresta grafo_Aresta0 = grafo1.retiraAresta(0, 2325);
      assertEquals(1003, grafo1.numVertices());
      assertNull(grafo_Aresta0);
  }

    /**
     * Given a graph and its transpose,
     * when an insertion causes an invalid internal index during a subsequent transpose,
     * then an ArrayIndexOutOfBoundsException is expected.
     *
     * Note: This test preserves the original oracle which verifies the thrown exception.
     */
    @Test(timeout = 4000)
    public void test3() throws Throwable {
        // Given
        Grafo grafo0 = new Grafo(DEFAULT_SIZE);

        // When
        grafo0.insereAresta(968, 0, 968);
        Grafo grafo1 = grafo0.grafoTransposto();
        grafo1.insereAresta(0, 1003, 968);

        // Then - expect ArrayIndexOutOfBoundsException when transposing
        try {
            grafo1.grafoTransposto();
            fail("Expecting exception: ArrayIndexOutOfBoundsException");
        } catch (ArrayIndexOutOfBoundsException e) {
            // preserve EvoSuite's verifyException behavior to keep original failure diagnostics
            verifyException("ds.Grafo", e);
        }
    }

    /**
     * Given an empty adjacency list request,
     * when primeiroListaAdj(0) is invoked,
     * then the graph size remains DEFAULT_SIZE.
     */
  @Test(timeout = 4000)
  public void test4()  throws Throwable  {
      Grafo grafo0 = new Grafo(1003);
      grafo0.primeiroListaAdj(0);
      assertEquals(1003, grafo0.numVertices());
  }

    /**
     * Given a graph with one inserted edge,
     * when its transpose is obtained and existence of the reversed edge is queried,
     * then the edge should exist and both graphs retain their vertex counts.
     */
  @Test(timeout = 4000)
  public void test5()  throws Throwable  {
      Grafo grafo0 = new Grafo(1003);
      grafo0.insereAresta(937, 0, 937);
      Grafo grafo1 = grafo0.grafoTransposto();
      boolean boolean0 = grafo1.existeAresta(0, 937);
      assertEquals(1003, grafo0.numVertices());
      assertTrue(boolean0);
      assertEquals(1003, grafo1.numVertices());
  }

    /**
     * Given a graph created with ALT_SIZE vertices,
     * when numVertices() is queried,
     * then it returns ALT_SIZE.
     */
  @Test(timeout = 4000)
  public void test6()  throws Throwable  {
      Grafo grafo0 = new Grafo(1597);
      int int0 = grafo0.numVertices();
      assertEquals(1597, int0);
  }

    /**
     * Given a graph with one inserted edge,
     * when its transpose is obtained and existence of an out-of-range edge is queried,
     * then the query returns false and the transposed graph retains its vertex count.
     */
  @Test(timeout = 4000)
  public void test7()  throws Throwable  {
      Grafo grafo0 = new Grafo(1003);
      grafo0.insereAresta(968, 0, 968);
      Grafo grafo1 = grafo0.grafoTransposto();
      boolean boolean0 = grafo1.existeAresta(0, 1003);
      assertEquals(1003, grafo1.numVertices());
      assertFalse(boolean0);
  }
}