/**
 * Unit and regression tests for ds.Fila.
 *
 * Requirement traceability:
 * - REQ-FILA-001: Basic queue operations must follow FIFO semantics.
 * - REQ-FILA-002: Dequeue on empty queue must raise a clear exception.
 *
 * The original autogenerated tests have been improved to include:
 * - Given-When-Then structure.
 * - Additional assertions with descriptive messages.
 * - Category markers for selective execution.
 */
interface UnitTest {}
interface RegressionTest {}

public class EvoAITest extends Fila_ESTest_scaffolding {

  /**
   * Given an empty queue, when an element is enqueued and imprime() is called,
   * then the queue should no longer be empty, the printed representation should
   * contain the enqueued element, and dequeuing should return the enqueued element.
   *
   * Requirement: REQ-FILA-001
   */
  @Test(timeout = 4000)
  @Category(UnitTest.class)
  public void test0()  throws Throwable  {
      // Given
      Fila fila0 = new Fila();
      assertTrue("Newly created queue should be empty", fila0.vazia());

      // When: enqueue an element and capture printed output
      final String value = "BFvX4s";
      PrintStream originalOut = System.out;
      ByteArrayOutputStream baos = new ByteArrayOutputStream();
      System.setOut(new PrintStream(baos));
      try {
          fila0.enfileira(value);
          // Then: the queue should report non-empty
          assertFalse("Queue should not be empty after enqueuing an element", fila0.vazia());
          // When: ask the queue to print itself
          fila0.imprime();
      } finally {
          // Restore system out in all cases
          System.setOut(originalOut);
      }

      String printed = baos.toString("UTF-8");
      assertTrue("imprime() output should contain the enqueued value; actual: " + printed, printed.contains(value));

      // Additionally verify FIFO behavior for this simple case
      Object dequeued = fila0.desenfileira();
      assertEquals("Dequeued element should match enqueued element", value, dequeued);
      assertTrue("Queue should be empty after dequeuing the only element", fila0.vazia());
  }

  /**
   * Given an empty queue, when a dequeue is attempted, then an exception with a
   * clear message should be thrown and the queue should remain usable afterwards.
   *
   * Requirement: REQ-FILA-002
   */
  @Test(timeout = 4000)
  @Category(UnitTest.class)
  public void test1()  throws Throwable  {
      // Given
      Fila fila0 = new Fila();
      assertTrue("Precondition: queue must start empty for this test", fila0.vazia());

      // When / Then: attempt to dequeue from an empty queue and verify exception details
      try {
          fila0.desenfileira();
          fail("Expected an exception when dequeuing from an empty queue");
      } catch (Exception e) {
          // Verify the exception carries a helpful message
          String msg = e.getMessage();
          assertNotNull("Exception message should not be null", msg);
          assertTrue("Exception message should mention that the queue is empty",
                  msg.toLowerCase().contains("fila") || msg.toLowerCase().contains("vazia") || msg.toLowerCase().contains("empty"));
          // After the exceptional call, the queue should still be empty and usable
          assertTrue("Queue should remain empty after failed dequeue", fila0.vazia());
      }

      // And: the queue should remain usable after the exception
      fila0.enfileira("recover");
      assertFalse("Queue should accept new elements after previous error", fila0.vazia());
      Object recovered = fila0.desenfileira();
      assertEquals("Element enqueued after error should be dequeued intact", "recover", recovered);
      assertTrue("Queue should be empty after recovering dequeue", fila0.vazia());
  }

  /**
   * Given a queue, when multiple values including an empty string are enqueued,
   * then dequeues must return elements in FIFO order.
   *
   * Requirement: REQ-FILA-001
   */
  @Test(timeout = 4000)
  @Category(RegressionTest.class)
  public void test2()  throws Throwable  {
      Fila fila0 = new Fila();

      // Enqueue the original test value first to preserve the original assertion behavior
      final String first = "BFvX4s";
      final String second = ""; // boundary input: empty string
      fila0.enfileira(first);
      fila0.enfileira(second);

      // Basic state checks
      assertFalse("Queue should not be empty after enqueuing items", fila0.vazia());

      // Dequeue and verify order and values (FIFO)
      Object object0 = fila0.desenfileira();
      assertEquals("First dequeued element should match the first enqueued value", first, object0);

      Object object1 = fila0.desenfileira();
      assertEquals("Second dequeued element should match the second enqueued (empty string) value", second, object1);

      // Final state
      assertTrue("Queue should be empty after dequeuing all elements", fila0.vazia());
  }
}