package ds.seed9121;

import org.junit.Test;
import static org.junit.Assert.*;
import static org.evosuite.runtime.EvoAssertions.*;
import ds.Fila;
import org.evosuite.runtime.EvoRunner;
import org.evosuite.runtime.EvoRunnerParameters;
import org.junit.runner.RunWith;

/**
 * Improved and intention-revealing tests for ds.Fila.
 * Traceability:
 *  - REQ-001: Queue basic operations (enqueue, dequeue, isEmpty, print)
 *  - REQ-ERR-001: Dequeue from empty queue must raise an Exception
 *  - REQ-ERR-002: Printing a queue containing a null entry may raise NPE in the runtime printing facility
 *
 * Notes:
 *  - Tests keep the original structure and expected exceptions from the autogenerated tests.
 *  - Each test follows Given-When-Then comments and uses descriptive assertion messages.
 */
@RunWith(EvoRunner.class) @EvoRunnerParameters(mockJVMNonDeterminism = true, useVFS = true, useVNET = true, resetStaticState = true, useJEE = true) 
public class EvoAITest extends Fila_ESTest_scaffolding {

  /**
   * Given: a fresh queue
   * When: a null element is enqueued and the queue is asked to be printed
   * Then: the printing operation is expected to throw a NullPointerException (as observed in the SUT)
   *
   * Requirement: REQ-ERR-002
   */
  @Test(timeout = 4000)
  public void test0()  throws Throwable  {
      Fila fila0 = new Fila();
      fila0.enfileira((Object) null);
      // Undeclared exception!
      try { 
        fila0.imprime();
        fail("Expecting exception: NullPointerException");
      
      } catch(NullPointerException e) {
         //
         // no message in exception (getMessage() returned null)
         //
         verifyException("org.evosuite.runtime.System", e);
      }
  }

  /**
   * Given: a fresh queue
   * When: a dequeue is attempted on an empty queue
   * Then: an Exception is thrown indicating the queue is empty
   *
   * Requirement: REQ-ERR-001
   */
  @Test(timeout = 4000)
  public void test1()  throws Throwable  {
      Fila fila0 = new Fila();
      try { 
        fila0.desenfileira();
        fail("Expecting exception: Exception");
      
      } catch(Exception e) {
         //
         // Erro: A fila esta vazia
         //
         verifyException("ds.Fila", e);
      }
  }

  /**
   * Given: a fresh queue
   * When: a null element is enqueued and then dequeued, and then the queue is printed
   * Then: the queue should be empty after dequeue and printing should not throw
   *
   * Requirement: REQ-001
   */
  @Test(timeout = 4000)
  public void test2()  throws Throwable  {
      Fila fila0 = new Fila();
      fila0.enfileira((Object) null);
      fila0.desenfileira();
      fila0.imprime();
      assertTrue(fila0.vazia());
  }
}