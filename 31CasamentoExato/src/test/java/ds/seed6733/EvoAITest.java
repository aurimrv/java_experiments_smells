    private static Throwable expectException(Class<? extends Throwable> expected, Callable<?> action) {
        try {
            action.call();
            fail("Expected exception of type " + expected.getName() + " but no exception was thrown.");
            return null; // unreachable
        } catch (Throwable t) {
            Throwable actual = t;
            if (t instanceof InvocationTargetException && t.getCause() != null) {
                actual = t.getCause();
            }
            assertTrue("Expected exception of type " + expected.getName() + " but got " + actual.getClass().getName(),
                    expected.isInstance(actual));
            return actual;
        }
    }

